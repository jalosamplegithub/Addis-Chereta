-- Apply once to add sealed bid storage to an existing database.
CREATE TABLE IF NOT EXISTS auction_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_item_id BIGINT NOT NULL REFERENCES auction_items(id) ON DELETE CASCADE,
    bidder_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    bidder_username VARCHAR(50) NOT NULL,
    bidder_email VARCHAR(254) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (auction_item_id, bidder_id)
);
ALTER TABLE auction_bids ADD COLUMN IF NOT EXISTS bidder_username VARCHAR(50);
ALTER TABLE auction_bids ADD COLUMN IF NOT EXISTS bidder_email VARCHAR(254);
UPDATE auction_bids b
SET bidder_username=u.username, bidder_email=u.email
FROM users u
WHERE u.id=b.bidder_id AND (b.bidder_username IS NULL OR b.bidder_email IS NULL);
ALTER TABLE auction_bids ALTER COLUMN bidder_username SET NOT NULL;
ALTER TABLE auction_bids ALTER COLUMN bidder_email SET NOT NULL;
CREATE INDEX IF NOT EXISTS auction_bids_item_idx ON auction_bids (auction_item_id);
