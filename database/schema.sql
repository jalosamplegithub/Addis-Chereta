-- Addis Chereta account registration schema (PostgreSQL)
-- Run this file against the application's PostgreSQL database before starting the API.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    legal_name VARCHAR(180) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    gender VARCHAR(24) NOT NULL CHECK (gender IN ('male', 'female', 'prefer_not_to_say')),
    username VARCHAR(50) NOT NULL,
    password_hash TEXT NOT NULL,
    preferred_language VARCHAR(2) NOT NULL DEFAULT 'en'
        CHECK (preferred_language IN ('en', 'am', 'om')),
    role VARCHAR(20) NOT NULL DEFAULT 'bidder',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Procurement staff are created by an administrator; public sign-up stays bidder-only.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('bidder', 'staff', 'admin', 'evaluator', 'finance', 'auditor', 'procurement'));

-- Case-insensitive uniqueness prevents duplicate accounts such as User@site.com
-- and user@site.com, or two usernames that differ only by letter case.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
    ON users (LOWER(email));

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
    ON users (LOWER(username));

CREATE TABLE IF NOT EXISTS procurement_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    organization_name VARCHAR(180) NOT NULL,
    department VARCHAR(180),
    job_title VARCHAR(120),
    profile_photo_path TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE procurement_profiles
    ADD COLUMN IF NOT EXISTS profile_photo_path TEXT;

-- Optional administrator-only profile details. The login and role remain in users.
CREATE TABLE IF NOT EXISTS admin_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    department VARCHAR(180),
    job_title VARCHAR(120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add the default profile row when the first admin account already exists.
INSERT INTO admin_profiles (user_id, department, job_title)
SELECT id, 'System Administration', 'System Administrator'
FROM users
WHERE LOWER(username) = 'admin' AND role = 'admin'
ON CONFLICT (user_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS auction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    listing_intent VARCHAR(180) NOT NULL DEFAULT 'TO BE SELL',
    vehicle_type VARCHAR(100) NOT NULL,
    lot_number VARCHAR(60) NOT NULL,
    initial_price NUMERIC(14, 2) NOT NULL CHECK (initial_price >= 0),
    minimum_increment NUMERIC(14, 2) NOT NULL CHECK (minimum_increment > 0),
    maximum_price NUMERIC(14, 2) CHECK (maximum_price IS NULL OR maximum_price >= initial_price),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'closed', 'cancelled')),
    photo_path TEXT,
    document_path TEXT,
    document_name VARCHAR(255),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (ends_at > starts_at)
);

ALTER TABLE auction_items
    ADD COLUMN IF NOT EXISTS listing_intent VARCHAR(180) NOT NULL DEFAULT 'TO BE SELL';

-- Upgrade older installations that constrained listing labels to only "buy" or "sell".
ALTER TABLE auction_items
    DROP CONSTRAINT IF EXISTS auction_items_listing_intent_check;

ALTER TABLE auction_items
    ALTER COLUMN listing_intent TYPE VARCHAR(180),
    ALTER COLUMN listing_intent SET DEFAULT 'TO BE SELL';

UPDATE auction_items
SET listing_intent = CASE LOWER(listing_intent)
    WHEN 'sell' THEN 'TO BE SELL'
    WHEN 'buy' THEN 'ITEM TO BE BUY'
    ELSE listing_intent
END
WHERE LOWER(listing_intent) IN ('sell', 'buy');

CREATE UNIQUE INDEX IF NOT EXISTS auction_items_lot_number_unique
    ON auction_items (LOWER(lot_number));
CREATE INDEX IF NOT EXISTS auction_items_status_ends_at_idx
    ON auction_items (status, ends_at);
CREATE INDEX IF NOT EXISTS auction_items_created_by_idx
    ON auction_items (created_by);

CREATE TABLE IF NOT EXISTS auction_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_item_id BIGINT NOT NULL REFERENCES auction_items(id) ON DELETE CASCADE,
    bidder_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    bidder_username VARCHAR(50) NOT NULL,
    bidder_email VARCHAR(254) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (auction_item_id, bidder_id)
);
ALTER TABLE auction_bids ADD COLUMN IF NOT EXISTS bidder_username VARCHAR(50);
ALTER TABLE auction_bids ADD COLUMN IF NOT EXISTS bidder_email VARCHAR(254);
UPDATE auction_bids b
SET bidder_username=u.username, bidder_email=u.email
FROM users u
WHERE u.id=b.bidder_id AND (b.bidder_username IS NULL OR b.bidder_email IS NULL);
ALTER TABLE auction_bids ALTER COLUMN bidder_username SET NOT NULL;
ALTER TABLE auction_bids ALTER COLUMN bidder_email SET NOT NULL;
CREATE INDEX IF NOT EXISTS auction_bids_item_idx ON auction_bids (auction_item_id);

